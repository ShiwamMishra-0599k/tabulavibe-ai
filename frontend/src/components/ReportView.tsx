import type { AnalysisResult, Narrative, Profile } from '../lib/types'
import { formatCount, formatPercent, LOCALE } from '../lib/format'
import { chartTitle, type ChartKind } from '../lib/charts'
import { ChartView, KpiCards, ResultsTable } from './Dashboard'
import { NarrativeText } from './AiNarrative'

interface Props {
  profile: Profile
  result: AnalysisResult
  narrative: Narrative | null
  chartKind: ChartKind
  measureKey: string
  preparedAt: Date
}

/** Management-report layout. Printed via the browser (Print → Save as PDF). */
export function ReportView({ profile, result, narrative, chartKind, measureKey, preparedAt }: Props) {
  const { dataset } = profile
  const filters = result.spec.filters
  const warnings = profile.issues.filter((i) => i.severity === 'warning')
  return (
    <article id="report" className="mx-auto grid max-w-4xl gap-6 rounded-xl border border-line bg-surface p-6 print:border-0 print:p-0">
      <header className="border-b border-line pb-4">
        <p className="text-xs font-medium uppercase tracking-wide text-ink-muted">TabulaVibe AI · Business report</p>
        <h1 className="mt-1 text-2xl font-semibold text-ink">{chartTitle(result, measureKey)}</h1>
        <p className="mt-1 text-sm text-ink-2">
          Source: {dataset.file_name || 'uploaded file'}
          {dataset.sheet_name ? ` (sheet "${dataset.sheet_name}")` : ''} · Prepared{' '}
          {preparedAt.toLocaleDateString(LOCALE, { day: 'numeric', month: 'long', year: 'numeric' })}
        </p>
      </header>

      <section className="print-avoid-break">
        <h2 className="mb-2 text-lg font-semibold text-ink">Scope</h2>
        <ul className="list-disc pl-5 text-sm text-ink-2">
          <li>
            {formatCount(result.rows_analyzed)} of {formatCount(dataset.row_count)} rows analysed across {dataset.column_count} columns.
          </li>
          <li>{result.spec.remove_duplicates ? 'Exact duplicate rows were excluded.' : `Duplicate rows were kept (${dataset.duplicate_row_count} found).`}</li>
          {result.spec.merge_label_variants && <li>Labels differing only by letter case or spacing were merged.</li>}
          {filters.length === 0 && <li>No filters applied.</li>}
          {filters.map((f) => (
            <li key={f.column}>
              Filter on {f.column}: {f.values ? f.values.join(', ') : `${f.start ?? 'start'} to ${f.end ?? 'end'}`}
            </li>
          ))}
          {result.notes.map((n) => (
            <li key={n}>{n}</li>
          ))}
        </ul>
      </section>

      <section>
        <h2 className="mb-3 text-lg font-semibold text-ink">Key figures</h2>
        <KpiCards result={result} />
      </section>

      {result.grouping && result.rows.length > 0 && (
        <>
          {chartKind !== 'table' && (
            <section className="print-avoid-break">
              <h2 className="mb-3 text-lg font-semibold text-ink">Chart</h2>
              <ChartView result={result} kind={chartKind} measureKey={measureKey} />
            </section>
          )}
          <section>
            <h2 className="mb-3 text-lg font-semibold text-ink">Detailed results</h2>
            <ResultsTable result={result} />
          </section>
        </>
      )}

      {narrative && (
        <section className="print-avoid-break rounded-lg border border-line p-4">
          <h2 className="mb-2 text-lg font-semibold text-ink">Commentary</h2>
          <NarrativeText narrative={narrative} />
        </section>
      )}

      <section className="print-avoid-break">
        <h2 className="mb-2 text-lg font-semibold text-ink">Data quality</h2>
        <p className="text-sm text-ink-2">
          {formatCount(dataset.missing_cell_count)} missing cells ({formatPercent(dataset.missing_cell_pct)}) and{' '}
          {formatCount(dataset.duplicate_row_count)} duplicate rows were detected. Missing and invalid values are excluded from calculations
          and were not altered.
        </p>
        {warnings.length > 0 && (
          <ul className="mt-2 list-disc pl-5 text-sm text-ink-2">
            {warnings.map((w) => (
              <li key={w.message}>{w.message}</li>
            ))}
          </ul>
        )}
      </section>

      <footer className="border-t border-line pt-3 text-xs text-ink-muted">
        Figures were calculated by TabulaVibe AI from the uploaded file. Definitions are listed under each key figure. This report was
        generated by a demonstration tool and should be reviewed before it is relied on for decisions.
      </footer>
    </article>
  )
}
